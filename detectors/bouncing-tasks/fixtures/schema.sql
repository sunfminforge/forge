-- The L3 tables the detector reads, as guild 0.1.33 makes them.
CREATE TABLE flow (id INTEGER PRIMARY KEY, task INTEGER NOT NULL, at INTEGER NOT NULL, record TEXT NOT NULL);
CREATE TABLE settlements (id INTEGER PRIMARY KEY, task TEXT NOT NULL, role TEXT NOT NULL, at INTEGER NOT NULL, tokens INTEGER, seconds INTEGER NOT NULL);
CREATE TABLE steps (id INTEGER PRIMARY KEY, task TEXT NOT NULL, role TEXT NOT NULL, at INTEGER NOT NULL, line TEXT NOT NULL);
